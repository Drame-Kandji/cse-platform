package sn.cse.fournisseurs.domain.model;

/** Catégories de matériel (contrat §1), utilisées comme spécialités des fournisseurs. */
public enum CategorieMateriel {
  /** Engins et véhicules (pelles, camions-bennes, niveleuses…). */
  MATERIEL_ROULANT,
  /** Outillage de chantier (groupes électrogènes, compacteurs manuels…). */
  OUTILLAGE,
  /** Matériel informatique et télécom. */
  EQUIPEMENT_INFORMATIQUE,
  /** Consommables (ciment, bitume, carburant…). */
  CONSOMMABLE
}
