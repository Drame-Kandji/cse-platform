package sn.cse.suivi.domain.model;

/** Catégorie fonctionnelle d'un matériel. */
public enum CategorieMateriel {
  /** Engins et véhicules (pelles, bulldozers, camions…). */
  MATERIEL_ROULANT,
  /** Outillage de chantier (compacteurs à main, groupes électrogènes…). */
  OUTILLAGE,
  /** Matériel informatique des bureaux de chantier. */
  EQUIPEMENT_INFORMATIQUE,
  /** Consommables suivis en parc. */
  CONSOMMABLE
}
